using RPGCharacterManager.Core.Models.Shell;

namespace RPGCharacterManager.Core.Abstractions.Presentation;

/// <summary>
/// Поставщик элементов оболочки приложения.
///
/// Каждая подсистема регистрирует собственную реализацию и добавляет свои разделы
/// навигации, команды и типы документов. Главное окно при этом остаётся неизменным —
/// требование расширяемости без изменения ядра.
///
/// У раздела ровно один вход — пункт панели навигации. Дублирующих поверхностей,
/// верхнего меню и панели инструментов, в оболочке нет: одно и то же действие,
/// доступное в трёх местах, заставляет пользователя гадать, чем эти места различаются.
/// </summary>
public interface IShellContributor
{
    /// <summary>Порядок применения вклада. Меньшее значение обрабатывается раньше.</summary>
    int Order => 0;

    /// <summary>
    /// Возвращает разделы панели навигации.
    /// </summary>
    /// <returns>Последовательность описаний разделов.</returns>
    IEnumerable<NavigationItemContribution> GetNavigationItems() => [];

    /// <summary>
    /// Возвращает команды, не являющиеся разделами: изменение масштаба,
    /// открытие папок, сведения о программе.
    /// </summary>
    /// <returns>Последовательность описаний команд.</returns>
    IEnumerable<CommandContribution> GetCommands() => [];
}
