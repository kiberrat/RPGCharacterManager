    public static IReadOnlyList<Ability> GetAbilities(Character character)
    {
        ArgumentNullException.ThrowIfNull(character);

        if (character.GameSystemId != Dnd5eSystemId)
        {
            return [];
        }

        var className = character.Class?.SystemName;
        if (string.IsNullOrWhiteSpace(className) || !Features.TryGetValue(className, out var features))
        {
            return [];
        }

        return features
            .Where(feature => character.Level >= feature.Level)
            .Select(feature => new Ability
            {
                Id = StableId(className, feature.Level, feature.Name),
                Name = feature.Name,
                SystemName = $"{className}_{feature.Level}_{feature.Name}",
                Description = feature.Description,
                Category = $"{Category} — {character.Class!.Name}",
                Formula = feature.Formula,
                RechargeRule = feature.RechargeRule,
                Requirements = $"класс = \"{className}\" и уровень >= {feature.Level}",
                GameSystemId = character.GameSystemId,
                IsSystem = true,
                Source = "Книга игрока D&D 5e"
            })
            .ToList();
    }

    private static Feature F(
        int level,
        string name,
        string description,
        string? formula = null,
        string? recharge = null) =>
        new(level, name, description, formula, recharge);

    private static Feature Asi(int level) =>
        F(level, $"Увеличение характеристик ({level} уровень)",
            "Увеличьте одну характеристику на 2 или две характеристики на 1 (обычно не выше 20) либо используйте разрешённую Мастером черту.");

    private static Guid StableId(string className, int level, string name)
    {
        var bytes = System.Security.Cryptography.SHA256.HashData(
            System.Text.Encoding.UTF8.GetBytes($"dnd5e:{className}:{level}:{name}"));
        return new Guid(bytes[..16]);
    }
