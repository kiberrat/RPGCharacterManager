using System.Text;
using RPGCharacterManager.Ai.Tools;
using RPGCharacterManager.Core.Abstractions.Ai;
using RPGCharacterManager.Core.Abstractions.Content;
using RPGCharacterManager.Core.Models.Ai;
using RPGCharacterManager.Core.Models.Settings;

namespace RPGCharacterManager.Ai;

/// <summary>
/// Указания, которые получает языковая модель.
///
/// Указания строятся заново перед каждым запросом и включают состав видов
/// объектов этой базы. Модель не знает игровых систем приложения и не должна
/// опираться на правила игр, которые знает сама: единственный источник сведений
/// об игре — база пользователя, прочитанная инструментами.
/// </summary>
internal static class AiPrompt
{
    /// <summary>
    /// Строит указания модели.
    /// </summary>
    /// <param name="content">Служба контента.</param>
    /// <param name="scope">Что известно о происходящем в приложении.</param>
    /// <param name="style">Стиль ответов, выбранный пользователем.</param>
    /// <returns>Текст указаний.</returns>
    public static string Build(IContentService content, AiScope scope, AiStyle style)
    {
        var builder = new StringBuilder();

        builder.AppendLine(
            """
            Ты — встроенный помощник настольного приложения «RPG Character Manager».
            Отвечай только на русском языке, в том числе в названиях создаваемых объектов.

            Что важно понимать об этом приложении:
            - Оно не знает заранее ни одной игры. Ни D&D, ни Pathfinder, ни любой другой.
              Расы, классы, заклинания, оружие, ресурсы и правила — это записи в базе,
              созданные пользователем или загруженные контент-паком.
            - Поэтому никогда не выдавай за истину правила игр, которые знаешь сам.
              Прежде чем утверждать что-либо об объекте, прочитай его инструментом.
            - Одна и та же просьба в разных играх решается по-разному: смотри, что есть
              в базе, а не что принято в известных тебе системах.
            """);

        builder.AppendLine().AppendLine("О чём тебя может попросить пользователь:");

        foreach (var capability in AiCapabilities.All)
        {
            builder.Append("- ").Append(capability.Title).Append(": ").AppendLine(capability.Hint);
        }

        builder.AppendLine().AppendLine("Виды игровых объектов в этой базе:");

        foreach (var type in content.Types)
        {
            builder.Append("- ").Append(type.Id).Append(" — ").Append(type.DisplayName)
                .Append(": ").AppendLine(type.Description);
        }

        builder.AppendLine().AppendLine(
            $"""
             Порядок работы:
             1. Имена полей не придумывай: перед созданием и изменением объекта вызывай {DescribeTypeTool.ToolName}.
             2. Формулу перед записью проверяй инструментом {CheckFormulaTool.ToolName}.
             2.1. Проверки — не работа, а подготовка к ней. Узнав поля и проверив формулу,
                  сразу вызывай {CreateObjectTool.ToolName} или {UpdateObjectTool.ToolName}: останавливаться
                  после подготовки нельзя, иначе просьба останется невыполненной.
             3. Ссылку на другой объект задавай его точным названием или идентификатором.
             4. Если у вида есть поле gameSystem, заполняй его названием игровой системы,
                о которой говорит пользователь.
             5. Изменения ты только предлагаешь. Инструменты {CreateObjectTool.ToolName}, {CopyObjectTool.ToolName},
                {UpdateObjectTool.ToolName} и {AddListItemTool.ToolName} ничего не записывают: подтверждает
                и применяет их пользователь кнопкой «Применить». Никогда не говори, что объект уже
                создан или сохранён, — говори, что предложение готово и ждёт подтверждения.
             6. Предложение существует, только если ты вызвал инструмент. Описывать поля объекта
                и сообщать «предложение готово», не вызвав {CreateObjectTool.ToolName}, запрещено:
                пользователь увидит текст, но в приложении не появится ничего, и он останется
                обманутым. Если создать объект нужно — вызывай инструмент, а не рассказывай о нём.
             7. Удалять данные ты не можешь и не предлагаешь.
             8. Один вызов — один объект. Несколько объектов создавай несколькими вызовами.
             9. Если сведений не хватает, спроси пользователя, а не выдумывай значения.
                Игровую систему не спрашивай, если в базе она одна или пользователь её не называл:
                оставь поле gameSystem пустым, объект всё равно будет создан.
             10. Закончив работу, коротко перечисли, что предложено и что осталось сделать вручную.
             11. Рассуждай про себя, не выводя ход мысли в ответ: пользователю нужен итог.
             """);

        if (scope.CharacterName is { Length: > 0 })
        {
            builder.AppendLine().Append("Пользователь работает с персонажем «")
                .Append(scope.CharacterName)
                .Append("» (идентификатор ").Append(scope.CharacterId)
                .AppendLine("). Учитывай его в советах и читай лист инструментом " +
                    ReadCharacterTool.ToolName + ".");
        }

        builder.AppendLine().Append("Стиль ответа: ").AppendLine(Describe(style));

        return builder.ToString();
    }

    /// <summary>
    /// Напоминание модели, остановившейся, не доведя работу до конца.
    ///
    /// Небольшие модели охотно выполняют подготовку — читают поля вида, проверяют
    /// формулу — и на этом замолкают, так и не вызвав инструмент создания.
    /// Одно напоминание обходится дешевле, чем ответ, в котором ничего не сделано.
    /// </summary>
    public const string Reminder =
        "Ты остановился, не закончив. Если для просьбы нужно создать или изменить объект — " +
        "вызови нужный инструмент прямо сейчас, подготовки уже достаточно. " +
        "Если делать больше нечего — коротко ответь текстом, что именно предложено.";

    /// <summary>
    /// Строит указания для разбора части источника.
    /// </summary>
    /// <param name="source">Название источника.</param>
    /// <param name="step">Номер части.</param>
    /// <param name="total">Общее количество частей.</param>
    /// <returns>Текст указаний.</returns>
    public static string BuildAnalysis(string source, int step, int total) =>
        $"""
         Разбери часть {step} из {total} источника «{source}».

         Найди в тексте игровые объекты и подготовь предложения их создать.
         Для каждого найденного объекта:
         - определи вид из перечня видов этой базы;
         - вызови {DescribeTypeTool.ToolName}, если ещё не знаешь полей этого вида;
         - проверь инструментом {FindObjectsTool.ToolName}, нет ли такого объекта в базе, и пропусти его, если есть;
         - вызови {CreateObjectTool.ToolName} — по одному вызову на объект.

         В поле source укажи «{source}». Не выдумывай объектов, которых в тексте нет,
         и не дополняй их сведениями из известных тебе игр. Если в части нет игровых
         объектов, так и напиши одной строкой и не вызывай инструменты.
         """;

    /// <summary>
    /// Описывает выбранный стиль ответа.
    /// </summary>
    /// <param name="style">Стиль ответа.</param>
    /// <returns>Указание модели.</returns>
    private static string Describe(AiStyle style) => style switch
    {
        AiStyle.Brief => "коротко, только суть, без вступлений и повторов вопроса.",
        AiStyle.GameMaster =>
            "как мастер игры — живым языком, с короткими описаниями обстановки, " +
            "но не в ущерб точности значений.",
        AiStyle.Technical =>
            "технически — перечнем полей и значений, формулы приводи выражениями, " +
            "без художественных описаний.",
        _ => "подробно — поясняй, почему выбраны именно такие значения.",
    };
}
