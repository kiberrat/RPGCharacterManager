namespace RPGCharacterManager.UI.ViewModels.Documents;

/// <summary>
/// Документ, показывающий конкретного персонажа.
///
/// По этому признаку оболочка узнаёт, чьи значения доступны панели бросков:
/// пока открыт лист персонажа, формула «1d20 + Ловкость» берёт ловкость именно
/// у него. Документ, не связанный с персонажем, признак не объявляет, и панель
/// работает без значений — так же, как за столом без листа.
/// </summary>
public interface ICharacterDocument
{
    /// <summary>Идентификатор показанного персонажа.</summary>
    Guid CharacterId { get; }

    /// <summary>Имя показанного персонажа.</summary>
    string CharacterName { get; }
}
